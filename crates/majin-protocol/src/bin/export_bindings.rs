//! Emits the TypeScript mirror of the wire protocol.
//!
//! Run via `pnpm generate:protocol`. The output is committed, and CI re-runs
//! this and fails on a diff, so the Rust and TypeScript views of the protocol
//! cannot drift apart.

use std::{fs, path::PathBuf};

use majin_protocol::{
    ApiError, ClientMessage, LoginRequest, MAX_COLS, MAX_ROWS, MIN_COLS, MIN_ROWS,
    PROTOCOL_VERSION, ServerInfo, ServerMessage, SessionStatus, TerminalErrorCode, TerminalSize,
    close_code,
};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let out_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/protocol/src/generated/protocol.ts");

    let mut out = String::new();
    out.push_str(
        "// @generated by `pnpm generate:protocol` from crates/majin-protocol/src/lib.rs\n\
         // Do not edit by hand. Run the command above after changing the Rust types.\n\n",
    );

    out.push_str(&format!(
        "export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n\n"
    ));

    out.push_str("/** Bounds the PTY layer will actually accept. */\n");
    out.push_str(&format!("export const MIN_COLS = {MIN_COLS};\n"));
    out.push_str(&format!("export const MIN_ROWS = {MIN_ROWS};\n"));
    out.push_str(&format!("export const MAX_COLS = {MAX_COLS};\n"));
    out.push_str(&format!("export const MAX_ROWS = {MAX_ROWS};\n\n"));

    out.push_str(
        "/**\n \
         * WebSocket close codes in the application-private range (4000-4999).\n \
         * `unauthorized` is distinct so the client can return to the login screen\n \
         * instead of retrying a reconnect that can never succeed.\n \
         */\n",
    );
    out.push_str("export const CloseCode = {\n");
    out.push_str(&format!("  normal: {},\n", close_code::NORMAL));
    out.push_str(&format!("  unauthorized: {},\n", close_code::UNAUTHORIZED));
    out.push_str(&format!("  sessionLimit: {},\n", close_code::SESSION_LIMIT));
    out.push_str(&format!(
        "  protocolError: {},\n",
        close_code::PROTOCOL_ERROR
    ));
    out.push_str(&format!("  shellExited: {},\n", close_code::SHELL_EXITED));
    out.push_str("} as const;\n\n");
    out.push_str("export type CloseCode = (typeof CloseCode)[keyof typeof CloseCode];\n\n");

    // Everything lands in one file, so ts-rs never needs to emit cross-file
    // imports and the default config is all we need.
    let cfg = Config::new();

    for decl in [
        TerminalSize::decl(&cfg),
        TerminalErrorCode::decl(&cfg),
        ClientMessage::decl(&cfg),
        ServerMessage::decl(&cfg),
        SessionStatus::decl(&cfg),
        LoginRequest::decl(&cfg),
        ApiError::decl(&cfg),
        ServerInfo::decl(&cfg),
    ] {
        out.push_str(&format!("export {decl}\n\n"));
    }

    if let Some(parent) = out_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&out_path, out)?;
    println!("wrote {}", out_path.display());
    Ok(())
}
